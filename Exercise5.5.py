# 5.5 ALIEN COLORS 3
# Ubah rangkaian if-else dari latihan 5-4 menjadi if-elif-else.
# Jika alien berwarna hijau, pemain mendapatkan 5 poin.
# Jika alien berwarna kuning, pemain mendapatkan 10 poin.
# Jika alien berwarna merah, pemain mendapatkan 15 poin.
# Buat tiga versi program agar setiap warna menghasilkan pesan yang sesuai.

# Menentukan warna alien
alien_color = "green"

# Memeriksa warna alien
if alien_color == "green":
    print("Kamu mendapatkan 5 poin!")
elif alien_color == "yellow":
    print("Kamu mendapatkan 10 poin!")
else:
    print("Kamu mendapatkan 15 poin!")

# Menentukan warna alien
