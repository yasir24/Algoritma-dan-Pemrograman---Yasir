# 4.4 ONE MILLIIONS
# Buat sebuah list yang berisi angka 1 sampai 1.000.000.
# Gunakan for loop untuk menampilkan seluruh angka dalam list.
# Jika proses menampilkan angka terlalu lama, hentikan dengan CTRL + C atau tutup jendela output.

# Membuat list angka 1 sampai 1.000.000
numbers = list(range(1, 1000001))

# Menampilkan seluruh angka
for number in numbers:
    print(number)