# Membuat daftar hewan
animals = ["Kucing", "Kelinci", "Hamster"]

# Menampilkan nama setiap hewan
for animal in animals:
    print(animal)

# Menampilkan pernyataan tentang setiap hewan
for animal in animals:
    print(f"{animal} bisa menjadi hewan peliharaan yang menyenangkan.")

# Menampilkan kesamaan ketiga hewan
