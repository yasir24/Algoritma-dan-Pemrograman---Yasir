# Buat operasi penjumlahan, pengurangan, perkalian, dan pembagian yang masing-masing menghasilkan 
# angka 8. Setiap operasi harus ditampilkan menggunakan print().
print(f"Penjumlahan: 5 + 3 = {5 + 3}")
print(f"Pengurangan: 10 - 2 = {10 - 2}")
print(f"Perkalian: 4 * 2 = {4 * 2}")
print(f"Pembagian: 16 / 2 = {16 / 2}") # Dalam Python, operator / menghasilkan tipe data float (angka desimal). Jadi, meskipun hasilnya 8 secara matematis, Python menampilkannya sebagai 8.0