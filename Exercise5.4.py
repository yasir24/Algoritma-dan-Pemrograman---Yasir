# 5.4 ALIEN COLORS 2
# Pilih warna alien seperti latihan 5-3.
# Buat rangkaian kondisi if-else.
# Jika warna alien hijau, pemain mendapatkan 5 poin.
# Jika warna alien bukan hijau, pemain mendapatkan 10 poin.
# Buat dua versi program:
# - Versi pertama menjalankan blok if.
# - Versi kedua menjalankan blok else.

# Menentukan warna alien
alien_color = "green"

# Memeriksa warna alien
if alien_color == "green":
    print("Kamu mendapatkan 5 poin!")
else:
    print("Kamu mendapatkan 10 poin!")

 # Menentukan warna alien
